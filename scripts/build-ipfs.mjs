#!/usr/bin/env node
// Static copy of the guide for IPFS (mesasays.eth, gateway.mesasays.com): `npm run build:ipfs` -> out/
//
// Say needs a server (server actions, /say/threads, live thread pages), which a static export
// cannot have. For the length of the build only, the Say routes (app/say/page.tsx, [id]/, threads/)
// are set aside and /say becomes one static page pointing to https://mesasays.com/say;
// next.config.ts (MESASAYS_TARGET=ipfs) swaps the conversation block on restaurant pages for the
// same notice. app/say/actions.ts stays (type-checked, never bundled: nothing imports it then).
// The routes are always put back, even on failure or Ctrl-C, and a leftover from a killed run
// is restored at the next start.
import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readdirSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sayDir = join(root, "app/say");
const stashRoot = join(root, ".ipfs-build");
const stash = join(stashRoot, "say");
const ROUTES = ["page.tsx", "[id]", "threads"];
const out = join(root, "out");

const STATIC_SAY_PAGE = `// Generated by scripts/build-ipfs.mjs for the static IPFS build only. Never committed.
import type { Metadata } from "next";
import { SayNotice } from "@/components/say/SayStatic";
import { pageMetadata } from "@/lib/seo";

export const metadata: Metadata = pageMetadata({
  title: "Say: what people say about Mexico City restaurants",
  description: "Conversations about Mexico City restaurants live at https://mesasays.com/say.",
  path: "/say",
  robots: { index: false, follow: true },
});

export default function SayPage() {
  return (
    <main className="ms-page ms-say-page">
      <h1 className="ms-title say-page-title">What people say</h1>
      <SayNotice />
    </main>
  );
}
`;

function restore() {
  if (!existsSync(stash)) return;
  for (const name of ROUTES) {
    if (!existsSync(join(stash, name))) continue;
    rmSync(join(sayDir, name), { recursive: true, force: true });
    renameSync(join(stash, name), join(sayDir, name));
  }
  rmSync(stash, { recursive: true, force: true });
  console.log("[build:ipfs] app/say routes restored");
}

function run(command, args, env = {}) {
  const result = spawnSync(command, args, { cwd: root, stdio: "inherit", env: { ...process.env, ...env } });
  if (result.status !== 0) throw new Error(`${command} ${args.join(" ")} failed (${result.status ?? result.signal})`);
}

function countPages(dir) {
  if (!existsSync(dir)) return 0;
  return readdirSync(dir).filter((name) => existsSync(join(dir, name, "index.html"))).length;
}

for (const signal of ["SIGINT", "SIGTERM", "SIGHUP"]) {
  process.on(signal, () => {
    restore();
    process.exit(130);
  });
}

// A previous run killed hard (kill -9, power cut) left app/say in the stash: put it back first.
restore();

try {
  run("npm", ["run", "data:check"]);
  rmSync(out, { recursive: true, force: true });
  // Route types left by `next dev` / `next typegen` still list the Say pages moved aside above: drop them.
  rmSync(join(root, ".next", "dev", "types"), { recursive: true, force: true });
  rmSync(join(root, ".next", "types"), { recursive: true, force: true });
  mkdirSync(stash, { recursive: true });
  for (const name of ROUTES) renameSync(join(sayDir, name), join(stash, name));
  writeFileSync(join(sayDir, "page.tsx"), STATIC_SAY_PAGE);
  run("npx", ["next", "build"], {
    MESASAYS_TARGET: "ipfs",
    NEXT_PUBLIC_SITE_URL: process.env.NEXT_PUBLIC_SITE_URL || "https://mesasays.com",
  });
} finally {
  restore();
}

// Kubo serves ipfs-404.html for missing paths on subdomain and DNSLink gateways (eth.limo, ours).
if (existsSync(join(out, "404.html"))) copyFileSync(join(out, "404.html"), join(out, "ipfs-404.html"));
for (const required of ["index.html", "restaurants/index.html", "say/index.html", "llms.txt", "sitemap.xml", "data/restaurants.json"]) {
  if (!existsSync(join(out, required))) throw new Error(`[build:ipfs] missing out/${required}`);
}
let files = 0;
let bytes = 0;
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    const stat = statSync(path);
    if (stat.isDirectory()) walk(path);
    else {
      files += 1;
      bytes += stat.size;
    }
  }
};
walk(out);
console.log(
  `[build:ipfs] out/ ready: ${files} files, ${(bytes / 1e6).toFixed(1)} MB, ` +
    `${countPages(join(out, "restaurants"))} restaurant pages (en), ${countPages(join(out, "es/restaurantes"))} (es)`,
);
