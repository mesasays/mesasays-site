#!/usr/bin/env node

// Refreshes the MXN → USD / EUR reference rates shown next to peso prices.
// Source: European Central Bank reference rates via the free Frankfurter API (no key).
//
//   node scripts/update-fx.mjs

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const response = await fetch("https://api.frankfurter.dev/v1/latest?base=MXN&symbols=USD,EUR");
if (!response.ok) throw new Error(`Frankfurter API answered ${response.status}`);
const { date, rates } = await response.json();
if (!(rates?.USD > 0 && rates?.EUR > 0)) throw new Error("Missing USD or EUR rate");
const fx = { date, source: "European Central Bank reference rate (frankfurter.dev)", mxnTo: { USD: rates.USD, EUR: rates.EUR } };
writeFileSync(
  resolve(root, "lib/fx.ts"),
  `// Generated by scripts/update-fx.mjs — do not edit by hand.\nexport const fx = ${JSON.stringify(fx, null, 2)} as const;\n`,
);
console.log(fx);
